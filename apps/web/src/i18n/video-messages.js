export function videoText(language,original,values){
 if(typeof original!=='string')return original==null?'':String(original);
 if(!Object.hasOwn(VIDEO_MESSAGES,original))return original;
 const index=language==='en'?1:language==='zh-TW'?0:-1;
 let text=index>=0?VIDEO_MESSAGES[original][index]:original;
 if(language==='en'&&values){
  text=text.replace(/\{(\w+)\} (credits|ideas|seconds|materials|images)\b/g,(token,name,unit)=>Object.hasOwn(values,name)&&Number(values[name])===1?'{'+name+'} '+unit.slice(0,-1):token);
  if(Number(values.count)===1)text=text.replace(/^(basic |advanced |image |app )?(credits|materials)$/,(token,prefix='',unit)=>prefix+unit.slice(0,-1));
 }
 return values?text.replace(/\{(\w+)\}/g,(token,name)=>Object.hasOwn(values,name)?String(values[name]):token):text;
}
