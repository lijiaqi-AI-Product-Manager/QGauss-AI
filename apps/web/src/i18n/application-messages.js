export function applicationText(language,original,values){
  if(typeof original!=='string')return original==null?'':String(original);
  const index=language==='en'?1:language==='zh-TW'?0:-1;
  const message=index>=0&&Object.hasOwn(APPLICATION_MESSAGES,original)?APPLICATION_MESSAGES[original][index]:original;
  return values?message.replace(/\{(\w+)\}/g,(token,name)=>Object.hasOwn(values,name)?String(values[name]):token):message;
}
