export function paintingText(language,original,values){
 if(typeof original!=='string')return original==null?'':String(original);
 const known=Object.hasOwn(PAINTING_MESSAGES,original),index=language==='en'?1:language==='zh-TW'?0:-1;
 let text=known&&index>=0?PAINTING_MESSAGES[original][index]:original;
 if(language==='en'&&known&&values){
  text=text.replace(/\{(\w+)\} (reference images|membership credits|images|credits|ideas)\b/g,(token,name,unit)=>Object.hasOwn(values,name)&&Number(values[name])===1?'{'+name+'} '+unit.slice(0,-1):token);
  if(Number(values.count)===1)text=text.replace(/^(\s*)credits( \/ image|\s*)$/,(token,space,end)=>space+'credit'+end);
 }
 return values?text.replace(/\{(\w+)\}/g,(token,name)=>Object.hasOwn(values,name)?String(values[name]):token):text;
}
