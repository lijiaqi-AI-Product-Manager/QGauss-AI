export function chatText(language,original,values){
 if(typeof original!=='string')return original==null?'':String(original);
 const index=language==='en'?1:language==='zh-TW'?0:-1;
 let text=index>=0&&Object.hasOwn(CHAT_MESSAGES,original)?CHAT_MESSAGES[original][index]:original;
 if(language==='en'&&values&&Object.hasOwn(CHAT_MESSAGES,original)&&Number(values.count)===1)text=text.replace(/^(\s*)(models|files|sources|turns|conversations)(\s*)$/,(token,before,unit,after)=>before+unit.slice(0,-1)+after);
 if(language==='en'&&values&&Object.hasOwn(CHAT_MESSAGES,original))text=text.replace(/\{(\w+)\} (more |membership )?(credits|models|files|sources|turns|conversations)\b/g,(token,name,prefix,unit)=>Object.hasOwn(values,name)&&Number(values[name])===1?'{'+name+'} '+(prefix||'')+unit.slice(0,-1):token);
 return values?text.replace(/\{(\w+)\}/g,(token,name)=>Object.hasOwn(values,name)?String(values[name]):token):text;
}
