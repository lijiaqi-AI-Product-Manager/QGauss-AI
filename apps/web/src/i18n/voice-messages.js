export function voiceText(language,original,values){
  if(typeof original!=='string')return original==null?'':String(original);
  const index=language==='en'?1:language==='zh-TW'?0:-1;
  let message=index>=0&&Object.hasOwn(VOICE_MESSAGES,original)?VOICE_MESSAGES[original][index]:original;
  if(language==='en'&&values&&Object.hasOwn(VOICE_MESSAGES,original))message=message.replace(/\{(\w+)\} (reserved |sound )?(credits|segments|days|hours|characters|seconds|records)\b/g,(token,name,prefix,unit)=>Object.hasOwn(values,name)&&Number(values[name])===1?'{'+name+'} '+(prefix||'')+unit.slice(0,-1):token);
  return values?message.replace(/\{(\w+)\}/g,(token,name)=>Object.hasOwn(values,name)?String(values[name]):token):message;
}
